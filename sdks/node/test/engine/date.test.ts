import { describe, expect, it } from "vitest";
import {
  parseRfc3339Millis,
  toMillis,
} from "../../src/internal/engine/date.js";

describe("parseRfc3339Millis", () => {
  it.each([
    ["1970-01-01T00:00:00Z", 0],
    ["1970-01-01T00:00:00.123456789Z", 123],
    ["1970-01-01T00:00:00.5Z", 500],
    ["1970-01-01T01:00:00+01:00", 0],
    ["1969-12-31T23:00:00-01:00", 0],
    ["1969-12-31T23:59:59Z", -1000],
    ["2026-01-01t00:00:00z", 1767225600000],
    ["2026-01-01 00:00:00Z", 1767225600000],
    ["2024-02-29T00:00:00Z", 1709164800000],
    ["1970-01-01T00:00:00+23:59", -86340000],
    ["0001-01-01T00:00:00Z", -62135596800000],
    ["9999-12-31T23:59:59.999Z", 253402300799999],
  ])("%j is %d", (s, want) => {
    expect(parseRfc3339Millis(s)).toBe(want);
  });

  it.each([
    "2026-01-01",
    "2026-02-30T00:00:00Z",
    "2025-02-29T00:00:00Z",
    "2026-13-01T00:00:00Z",
    "2026-00-01T00:00:00Z",
    "2026-01-00T00:00:00Z",
    "2026-01-01T24:00:00Z",
    "2026-01-01T00:60:00Z",
    "2026-01-01T00:00:60Z",
    "2026-01-01T00:00:00",
    "2026-01-01T00:00:00+24:00",
    "2026-01-01T00:00:00+0100",
    "0000-01-01T00:00:00Z",
    "2026-01-01T00:00:00.Z",
    "2026-01-01T00:00:00Z\n",
    " 2026-01-01T00:00:00Z",
    "2026-01-01X00:00:00Z",
    "٢026-01-01T00:00:00Z",
    "２026-01-01T00:00:00Z",
    "2026-01-01T00:00:00+0١:00",
    "",
  ])("refuses %j", (s) => {
    expect(parseRfc3339Millis(s)).toBeUndefined();
  });
});

describe("toMillis", () => {
  it.each([
    ["1970-01-01T00:00:01Z", 1000],
    [1500, 1500],
    [1500.9, 1500],
    [-0.5, -1],
  ])("%j is %d", (v, want) => {
    expect(toMillis(v)).toBe(want);
  });

  it.each([
    [Number.NaN],
    [Number.POSITIVE_INFINITY],
    [Number.NEGATIVE_INFINITY],
    [true],
    [null],
    [undefined],
    [[1]],
    ["not a date"],
  ])("%j is invalid", (v) => {
    expect(toMillis(v)).toBeUndefined();
  });
});
